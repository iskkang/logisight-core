-- 한국산에 걸릴 수 있는 미국 추가관세 조항(HTS 99류).
--
-- 세율을 계산해서 더하지 않는다 ★
-- 각 조항은 "as provided for in U.S. note 33 subdivision (s)" 처럼 적용 범위를
-- 법령 주석에 맡기고, 주석 본문은 JSON API 가 아니라 14MB PDF 안에만 있다.
-- 예외 사슬("Except for products described in headings 9903.01.30–9903.01.33 …")도
-- 걸려 있어 적용 여부를 코드로 판정할 수 없다. 틀린 25%·40%를 자신 있게
-- 보여주느니 "대상일 수 있으니 확인하라"고 말하는 편이 안전하고, 실제로 더 쓸모 있다.
-- 지금 화면은 기본세율 3.4% 만 보여주고 끝나서 이용자가 다 알았다고 생각하고 간다.
--
-- 담는 것: 조항 번호, 명시된 세율, 원문, 적용 품목군 추정 접두사.
-- hs_prefixes 는 조항 문구에서 사람이 유추한 값이라 '확인 필요' 표시로만 쓴다.
create table if not exists public.us_additional_duty_provisions (
  id bigint generated by default as identity primary key,
  -- 99류 조항 번호(숫자만). 예: 9903.94.61 → '99039461'
  provision_code text not null unique check (provision_code ~ '^[0-9]{8}$'),
  -- 명시된 추가 세율. "The duty provided in the applicable subheading" 처럼
  -- 숫자가 아닌 조항은 null 로 두고 rate_text 만 남긴다.
  rate_percent numeric,
  rate_text text,
  -- 조항 원문(잘라서 저장). 이용자가 직접 판단할 수 있게 그대로 보여준다.
  description text not null,
  -- 적용 대상 품목군. null 이면 품목 제한 없이 한국산 전반에 걸리는 조항이다.
  hs_prefixes text[],
  -- 사람이 읽을 분류 이름. 예: '승용차·소형트럭'
  category_ko text,
  source_url text not null,
  is_active boolean not null default true,
  ingested_at timestamptz not null default now()
);

create index if not exists us_additional_duty_provisions_active_idx
  on public.us_additional_duty_provisions (is_active);

alter table public.us_additional_duty_provisions enable row level security;
grant select on public.us_additional_duty_provisions to anon, authenticated;
create policy "us additional duty provisions public read"
  on public.us_additional_duty_provisions for select to anon, authenticated using (is_active = true);
