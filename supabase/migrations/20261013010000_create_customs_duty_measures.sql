-- 시장 중립 관세 테이블. 미국(HTS)부터 쓴다.
--
-- 기존 eu_customs_measures 는 이름과 컬럼(cn_code)이 EU 전용이다. 미국을 넣으려고
-- us_customs_measures 를 또 만들면 같은 모양의 표가 둘이 되고, 조회 함수도 둘이
-- 된다 —— 이 저장소는 분류 파이프라인이 두 벌로 갈라져 정확도 측정이 엉뚱한
-- 코드를 재던 전력이 있다. 같은 일을 반복하지 않으려고 처음부터 market 열을 둔다.
-- EU 데이터는 지금 옮기지 않는다(동작 중인 기능이라 별도 작업으로 검증해 옮긴다).
create table if not exists public.customs_duty_measures (
  id bigint generated by default as identity primary key,
  market text not null,                    -- 'US' | 'EU'
  code text not null check (code ~ '^[0-9]{4,10}$'),
  -- null = 모든 원산지에 적용되는 기본세율. 'KR' = 한국산 특혜세율.
  origin_country text,
  measure_type text not null check (measure_type in ('THIRD_COUNTRY_DUTY', 'PREFERENCE')),
  -- 순수 종가세일 때만 채운다 ★
  -- "11.5¢/kg" 이나 "4.4% + 25¢/kg" 을 숫자 하나로 뭉개면 관세를 적게 계산해 주게
  -- 된다. EU 적재에서 지킨 규율이고(9,670건 중 과소계산 0건) 미국도 같게 간다.
  rate_percent numeric,
  rate_text text,
  title text not null,
  detail text,
  legal_basis text,
  source_url text not null,
  valid_from date,
  valid_to date,
  is_active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  ingested_at timestamptz not null default now(),
  -- NULLS NOT DISTINCT 가 필요하다 ★
  -- origin_country 는 "모든 원산지"일 때 NULL 이다. Postgres 는 기본적으로 NULL 을
  -- 서로 다른 값으로 보므로, 이게 없으면 기본세율 행에 ON CONFLICT 가 걸리지 않아
  -- 재적재할 때마다 같은 코드가 중복으로 쌓인다.
  unique nulls not distinct (market, code, origin_country, measure_type)
);

create index if not exists customs_duty_measures_lookup_idx
  on public.customs_duty_measures (market, code, origin_country, measure_type, is_active);

alter table public.customs_duty_measures enable row level security;
grant select on public.customs_duty_measures to anon, authenticated;
create policy "customs duty measures public read"
  on public.customs_duty_measures for select to anon, authenticated using (is_active = true);
