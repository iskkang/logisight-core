-- /customs(HS 분류) 조회 로그.
--
-- 왜 만드나 ★
-- 이 도구는 지금 어디에서도 링크되지 않고 사용 기록도 남기지 않는다. 그래서
-- "쓰이고 있나"에 답할 방법이 없었다. 공개로 밀기 전에 실제 사용량을 봐야 한다.
--
-- 공개 읽기 권한을 주지 않는다. description 은 이용자가 입력한 제품 설명이라
-- 영업상 민감할 수 있다. 서비스롤(supabaseAdmin)로만 쓰고 읽는다.
create table if not exists public.hs_classification_queries (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),

  -- 입력
  description text not null,
  origin_country text,
  destination_market text,
  destination_country text,

  -- 결과 요약. 원문 전체는 담지 않는다 —— 수요를 재는 데 필요한 만큼만.
  status text,                  -- candidate | needs_information
  top_cn8 text,
  candidate_count integer,
  duty_status text,             -- available | pending
  landed_cost_status text,      -- ready | needs_values | pending
  origin_status text,           -- qualified | not_qualified | needs_information | rule_unavailable

  duration_ms integer,
  error_message text
);

create index if not exists hs_classification_queries_created_idx
  on public.hs_classification_queries (created_at desc);

alter table public.hs_classification_queries enable row level security;
-- 정책을 하나도 만들지 않는다 = anon·authenticated 는 읽지도 쓰지도 못한다.
-- 서비스롤은 RLS 를 우회하므로 서버에서만 기록된다.
--
-- 테이블 GRANT 도 거둬 둔다. RLS 만으로도 막히지만, 프로젝트 기본 GRANT 가
-- anon·authenticated 에 남아 있어 "정책을 하나 잘못 추가하면 바로 공개"가 된다.
-- 의도를 권한에도 적어 둔다.
revoke all on public.hs_classification_queries from anon, authenticated;
