-- 시장 중립 수입 규제 표. 미국(PGA)부터 쓴다.
--
-- 미국은 FDA·FCC·CPSC·EPA·DOT 등 PGA 요건을 세번 단위 플래그로 관리하고 전체
-- 세번의 1/3 이상이 걸려 있다. 다만 권위 있는 원본(ACE REF-003)은 계정이 있어야
-- 받을 수 있고, 공개된 기계판독 배포처는 찾지 못했다. HTS 데이터 자체에도 기관
-- 정보가 거의 없다(FDA 1건·EPA 3건).
--
-- 그래서 EU 와 같은 방식으로 간다 —— eu_product_regulations 도 자동 수집기가
-- 아니라 수기로 넣은 17행이다. 류 단위로 "해당 가능성"을 알리고 공식 링크로
-- 보낸다. 세액처럼 틀리면 손해가 나는 값이 아니라, 모르고 지나치는 것이 손해인
-- 영역이라 이 수준이 실제로 쓸모 있다.
create table if not exists public.customs_product_regulations (
  id bigint generated by default as identity primary key,
  market text not null check (market in ('EU', 'US')),
  -- 적용 세번 접두사(2·4·6자리). 조회는 긴 접두사를 우선한다.
  code_prefix text not null check (code_prefix ~ '^[0-9]{2,10}$'),
  agency text not null,
  category text not null,
  title text not null,
  detail text not null,
  legal_basis text,
  source_url text not null,
  -- 제품 설명에 이 낱말이 있을 때만 보여준다. 비어 있으면 접두사만으로 보여준다.
  condition_keywords text[] not null default '{}',
  is_active boolean not null default true,
  source_version text,
  created_at timestamptz not null default now(),
  unique (market, code_prefix, agency, title)
);

create index if not exists customs_product_regulations_lookup_idx
  on public.customs_product_regulations (market, code_prefix, is_active);

alter table public.customs_product_regulations enable row level security;
grant select on public.customs_product_regulations to anon, authenticated;
create policy "customs product regulations public read"
  on public.customs_product_regulations for select to anon, authenticated using (is_active = true);

